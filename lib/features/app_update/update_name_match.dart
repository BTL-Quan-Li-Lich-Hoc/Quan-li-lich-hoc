/// Compare Vietnamese account names without losing accents.
String normalizeUpdateAccountName(String input) {
  final source = input.trim().replaceAll(RegExp(r'\s+'), ' ').toLowerCase();
  final result = StringBuffer();
  String? base;
  final marks = <int>[];

  void flush() {
    if (base == null) return;
    result.write(base);
    marks.sort((a, b) {
      final first = _markPriority(a);
      final second = _markPriority(b);
      return first == second ? a.compareTo(b) : first.compareTo(second);
    });
    for (final mark in marks) {
      result.writeCharCode(mark);
    }
    marks.clear();
  }

  for (final rune in source.runes) {
    final char = String.fromCharCode(rune);
    for (final unit in (_decomposed[char] ?? char).runes) {
      if (unit >= 0x0300 && unit <= 0x036f) {
        marks.add(unit);
      } else {
        flush();
        base = String.fromCharCode(unit);
      }
    }
  }
  flush();
  return result.toString();
}

int _markPriority(int mark) {
  if (mark == 0x031b) return 0;
  if (mark == 0x0302 || mark == 0x0306) return 1;
  if (mark == 0x0323) return 2;
  return 3;
}

